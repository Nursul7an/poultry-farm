#!/usr/bin/env node
// Builds the knowledge seed from one source:
//   packages/core/src/norms/aa-norms.json  → norm rows (farm_id null = Arbor Acres defaults)
//   docs/knowledge/0*.md                    → knowledge_article rows (one per handbook section)
// Writes: supabase/migrations/20261127000003_knowledge_seed.sql and apps/web/src/api/knowledge.generated.json (demo mode).
// Run: node scripts/gen-knowledge.mjs   (re-run after editing the JSON or the .md files; CI checks it is up to date)
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const norms = JSON.parse(readFileSync(join(root, 'packages/core/src/norms/aa-norms.json'), 'utf8'));

const SECTIONS = {
  '00': ['О справочнике', 'Сводка по двум руководствам'],
  '01': ['Посадка, брудер, корм и вода', 'Arbor Acres, разделы 1–2'],
  '02': ['Кормление, здоровье, биозащита', 'Arbor Acres, разделы 3–4'],
  '03': ['Микроклимат, свет, взвешивание, отлов', 'Arbor Acres, разделы 5–7'],
  '04': ['Учёт, показатели, решение проблем', 'Arbor Acres, приложения'],
  '05': ['Второе руководство (Cobb)', 'Руководство по выращиванию бройлеров, рус.'],
};

/** Drop references to extraction line numbers ("стр. ~830–845", "строки ~2697") that mean nothing to a reader. */
function clean(t) {
  return t
    .replace(/\s*\(→[^)]*\)/g, '')
    .replace(/\s*\(приложение должно брать один стандарт\)/g, '')
    .replace(/, в приложении брать °C\./g, '; верные значения — в °C.')
    .replace(/В источнике единица «мг\/л»\. По смыслу это ppm, но в приложении нужно хранить единицу так, как она стоит в тексте\./g, 'В справочнике единица указана как «мг/л»; по смыслу это ppm.')
    .replace(/\*\*Рекомендация:\*\* по умолчанию брать нормы Arbor Acres \(кросс фермы\), а нормы в приложении хранить как редактируемый справочник\./g, 'В приложении по умолчанию действуют нормы Arbor Acres; директор может изменить их для своей фермы.')
    .replace(/,?\s*(стр\.|строки|строк)\s*~?\s*[\d–\-, ~]+(?=[);\]\s.]|$)/g, '')
    .replace(/\(\s*[,;]?\s*\)/g, '')
    .replace(/\(\s*(Табл\.\s*\d+|табл\.\s*\d+|Рис\.\s*[\d–-]+)\s*[,;]\s*\)/g, '($1)')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

const articles = [];
for (const file of readdirSync(join(root, 'docs/knowledge')).filter((f) => /^0\d_.*\.md$/.test(f)).sort()) {
  const key = file.slice(0, 2);
  const [section, source] = SECTIONS[key] ?? ['Справочник', file];
  const text = readFileSync(join(root, 'docs/knowledge', file), 'utf8');
  const parts = text.split(/^## /m).slice(1); // level-2 sections
  let n = 0;
  for (const part of parts) {
    const [h2, ...rest] = part.split('\n');
    const body = rest.join('\n');
    if (key === '00' && /^База знаний|Файл/i.test(h2)) continue;
    const subs = body.split(/^### /m);
    const push = (title, md) => {
      let t = clean(title.replace(/^\d+(\.\d+)*\.?\s*/, ''));
      let extra = '';
      const cut = t.search(/\)\.\s/); // "Температура по возрасту (Табл. 2). С 27 дня…" → title + first line of body
      if (cut > 0) { extra = t.slice(cut + 3).trim(); t = t.slice(0, cut + 1); }
      const b = clean((extra ? extra + '\n\n' : '') + md);
      if (b.length > 20) articles.push({ id: `aa-${key}-${String(++n).padStart(2, '0')}`, section, title: t, body_md: b, source, sort: Number(key) * 100 + n });
    };
    if (subs.length > 1) {
      if (subs[0].trim().length > 40) push(h2, subs[0]);
      for (const s of subs.slice(1)) { const [h3, ...b3] = s.split('\n'); push(h3, b3.join('\n')); }
    } else push(h2, body);
  }
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sql = [
  '-- GENERATED by scripts/gen-knowledge.mjs — do not edit by hand.',
  '-- Arbor Acres norm defaults (farm_id null) and handbook articles.',
  'delete from public.norm where farm_id is null;',
  'delete from public.knowledge_article where farm_id is null;',
  ...Object.entries(norms).filter(([k]) => k !== '_source').map(([code, data]) =>
    `insert into public.norm (farm_id, code, data, updated_by) values (null, ${q(code)}, ${q(JSON.stringify(data))}::jsonb, null);`),
  ...articles.map((a) => `insert into public.knowledge_article (id, farm_id, section, title, body_md, source, sort) values (${q(a.id)}, null, ${q(a.section)}, ${q(a.title)}, ${q(a.body_md)}, ${q(a.source)}, ${a.sort});`),
  '',
].join('\n');
writeFileSync(join(root, 'supabase/migrations/20261127000003_knowledge_seed.sql'), sql);
writeFileSync(join(root, 'apps/web/src/api/knowledge.generated.json'), JSON.stringify(articles, null, 1) + '\n');
console.log(`norms: ${Object.keys(norms).length - 1} codes · articles: ${articles.length}`);
